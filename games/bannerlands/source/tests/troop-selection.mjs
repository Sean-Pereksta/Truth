import assert from 'node:assert/strict';
import {createTroopSelectionFilter,troopFilterShortcut} from '../../troop-selection.js';
const classes=new Map([[1,'infantry'],[2,'archer'],[3,'cavalry'],[4,'hero'],[5,'archer']]);
const alive=id=>classes.has(id),kind=id=>classes.get(id),filter=createTroopSelectionFilter();
let selection=new Set([1,2,3,4]);
selection=filter.apply('archer',selection,alive,kind);assert.deepEqual([...selection],[2]);
selection=filter.apply('cavalry',selection,alive,kind);assert.deepEqual([...selection],[3]);
selection=filter.apply('infantry',selection,alive,kind);assert.deepEqual([...selection],[1]);
selection=filter.apply('all',selection,alive,kind);assert.deepEqual([...selection],[1,2,3,4]);
selection=filter.apply('archer',selection,alive,kind);classes.delete(3);
selection=filter.apply('all',selection,alive,kind);assert.deepEqual([...selection],[1,2,4]);
filter.reset();selection=new Set([1]);selection=filter.apply('archer',selection,alive,kind);assert.equal(selection.size,0);assert.equal(filter.hasGroup,true);
selection=filter.apply('all',selection,alive,kind);assert.deepEqual([...selection],[1]);
filter.reset();selection=new Set([5]);selection=filter.apply('archer',selection,alive,kind);assert.deepEqual([...selection],[5]);
selection=new Set([1]);filter.sync(selection,alive);assert.equal(filter.hasGroup,false);assert.deepEqual([...filter.apply('all',selection,alive,kind)],[1]);
const event={shiftKey:true,ctrlKey:false,altKey:false,metaKey:false,key:'$',code:'Digit4'};
const context={panelOpen:false,formationMode:false,hasSelection:true};
assert.equal(troopFilterShortcut(event,context),'all');
assert.equal(troopFilterShortcut({...event,code:'Digit1',key:'!'},context),'infantry');
assert.equal(troopFilterShortcut({...event,code:'Digit2',key:'@'},context),'archer');
assert.equal(troopFilterShortcut({...event,code:'Digit3',key:'#'},context),'cavalry');
for(const change of [{panelOpen:true},{formationMode:true},{hasSelection:false}])assert.equal(troopFilterShortcut(event,{...context,...change}),null);
for(const change of [{shiftKey:false},{ctrlKey:true},{altKey:true},{metaKey:true}])assert.equal(troopFilterShortcut({...event,...change},context),null);
console.log('PASS troop selection filtering and shortcuts');
