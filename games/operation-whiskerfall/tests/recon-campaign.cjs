/* Run with Playwright on NODE_PATH. CHROME_PATH selects an installed browser. */
const assert = require('node:assert/strict');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const {chromium} = require('playwright');
(async () => {
  const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH||undefined});
  try {
    const page=await browser.newPage({viewport:{width:1280,height:720}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(pathToFileURL(path.resolve(__dirname,'../index.html')).href);
    await page.waitForFunction(()=>window.OW?.game?.ready);
    let oldBackup=null;
    if(process.env.MEOWQUEST_BASELINE){
      const prior=await browser.newPage();
      await prior.goto(pathToFileURL(path.resolve(process.env.MEOWQUEST_BASELINE,'index.html')).href);
      await prior.waitForFunction(()=>window.OW?.game?.ready);
      oldBackup=await prior.evaluate(()=>{
        const g=OW.game;g.start({slot:0,coop:true});
        // Use shipped commander death/loot handlers to create a real 1.9 save.
        for(const post of g.majorBosses()){
          const guard=g.world._createEnemy(g.world._spawns.get(post.id+'_commander'));
          g.killEnemy(guard,g.players[0]);
        }
        if(!g.berlinUnlocked()||g.campaignWon)throw Error('Old build did not open Berlin');
        g.toggleCoop();if(!g.save(false))throw Error('Old save failed');
        return OW.Save.export(0);
      });
      await prior.close();
    }
    const records=await page.evaluate(oldBackup=>{
      const g=OW.game,Q=OW.Recon,checks=[];
      function check(condition,message){if(!condition)throw Error(message);checks.push(message);}
      function place(p){g.players.forEach((hero,i)=>{hero.x=p.x+i*32;hero.y=p.y;});}
      function finishComic(title){
        check(g.comic?.book.title===title,'read '+title);
        while(g.comic)document.querySelector('.comic-reader .primary').click();
      }
      // Path search sweeps the same hero disk used by field movement across every
      // cell boundary. Relocation below isolates interact/save logic from input.
      function walk(grid,site,key,open,shortcut){
        const w={reconSite:site,state:{reconSwitch:open?2:0,claimed:shortcut}},p=Q.cell(site,'S'),goal=Q.cell(site,key);
        const queue=[p],seen=new Set();
        for(let i=0;i<queue.length;i++){
          const point=queue[i],id=point.x+','+point.y;if(seen.has(id))continue;seen.add(id);
          if(point.x===goal.x&&point.y===goal.y)return true;
          for(const [dx,dy] of [[1,0],[-1,0],[0,1],[0,-1]]){
            const next={x:point.x+dx*Q.tile,y:point.y+dy*Q.tile};
            if(!seen.has(next.x+','+next.y)&&[.25,.5,.75,1].every(t=>!grid.isBlocked.call(w,point.x+dx*Q.tile*t,point.y+dy*Q.tile*t,19)))queue.push(next);
          }
        }
        return false;
      }
      g.start({slot:0,coop:true});let p=g.players[0];
      check(g.world.regions.length===13,'13 connected regions');
      g.ui.showMenu('journal');choose('recon-assignments');
      check(!!document.querySelector('.quest-list [data-action="quest"]'),'fresh dossier opens the shipped assignment catalogue');
      choose('recon-dossier');g.ui.hideMenu();
      if(oldBackup){
        check(OW.Save.import(2,oldBackup),'backup generated by the 1.9 game imports');
        const original=OW.Save.read(2);
        check(!original.reconDossier&&original.reservePlayer?.id===1,'original format has the resting second hero');
        g.ui.slot=2;g.ui.mainTab='continue';g.ui.showMenu('main');choose('launch');
        check(g.slot===2&&g.world.berlinUnlocked()&&g.reconDossier.filed.length===12&&g.players[0].gold===original.players[0].gold,'title Continue preserves authentic open Berlin and archived credit');
        g.save(false);g.ui.slot=2;g.ui.mainTab='continue';g.ui.showMenu('main');choose('launch');
        check(g.reservePlayer.id===1&&g.reconDossier.filed.length===12&&g.players[0].gold===original.players[0].gold,'repeat Continue does not pay prior credits again');
        g.start({slot:0,load:true});p=g.players[0];
      }
      const clean=g.snapshot(), legacy=JSON.parse(JSON.stringify(clean));delete legacy.reconDossier;
      legacy.world.opened=legacy.world.opened.filter(id=>!id.startsWith('recon_'));
      const archive=JSON.parse(JSON.stringify(legacy));archive.world.liberated=Array.from({length:8},(_,i)=>'boss_'+i);
      check(OW.Save.write(2,archive)&&g.start({slot:2,load:true})&&g.world.berlinUnlocked()&&g.reconDossier.filed.length===12,'open Berlin before accepting final mission');
      archive.reservePlayer=archive.players.pop();archive.acceptedQuests=['main_berlin_final'];
      check(OW.Save.write(1,archive)&&g.start({slot:1,load:true}),'legacy active finale Continue');
      check(g.reconEvidenceCount()===12&&g.world.berlinUnlocked()&&g.reservePlayer.id===1,'returning Berlin clearance and resting hero');
      const restoredGold=g.players[0].gold;g.save(false);g.start({slot:1,load:true});
      check(g.players[0].gold===restoredGold&&g.reconDossier.filed.length===12,'archive migration is idempotent');
      archive.campaignWon=true;archive.world.liberated.push('boss_berlin');OW.Save.write(1,archive);g.start({slot:1,load:true});
      check(g.campaignWon&&g.reconEvidenceCount()===12,'completed campaign preserved');
      legacy.acceptedQuests=['escort_0'];legacy.missionRuns={escort_0:{questId:'escort_0',type:'escort',state:'active',hp:120,maxHp:320,x:1700,y:1520,elapsed:3,targetX:2250,targetY:2500}};
      OW.Save.write(1,legacy);g.start({slot:1,load:true});
      check(g.missionRuns.escort_0?.hp===120&&!g.reconEvidenceCount(),'unfinished mission preserved without premature credit');
      g.readyQuestTurnIns.add('escort_0');g.ui.showMenu('journal');
      const turnIn=document.querySelector('[data-action="recon-assignment"][data-value="escort_0"]');
      check(turnIn?.textContent.includes(g.questTurnInContact('escort_0').name),'legacy ready assignment names its recipient in the dossier');
      turnIn.click();
      check(g.ui.questId==='escort_0'&&!!document.querySelector('.quest-detail [data-action="track"]'),'legacy handoff opens the selected assignment and tracking action');
      g.ui.reconArchiveOpen=false;g.ui.hideMenu();
      g.start({slot:0,load:true});p=g.players[0];
      let nextRegion=0;
      function clearRegionalChain(region){
        for(let job=0;job<3;job++){
          const id='main_'+region+'_'+job,q=OW.Content.quests.find(q=>q.id===id),world=Q.surface(g);
          place(g.questContact(q));g.interact(p);
          check(g.ui.menu==='dialogue'&&g.acceptQuestFromNpc(id),'regional contact accepts '+id);
          g.ui.hideMenu();if(OW.FieldAssignments.route(g,q)===-1){place(g.assignmentSites(q).left);g.interact(p);}
          const loc=world.getLocation(q.target);
          place(loc);
          for(const guard of job===2?[q.target+'_commander']:loc.enemyIds){
            if(world.dead.has(guard))continue;
            const enemy=world._active.get(guard)||world._dormant.get(guard)||world._createEnemy(world._spawns.get(guard));
            if(enemy.boss){
              g.updateAdvancedEnemy(enemy,p,OW.Content.bosses[region],1/60);
              finishComic(enemy.name);
            }
            g.killEnemy(enemy,p);
          }
          g.updateLocations(.1);g.checkQuests();check(g.questProgress(q).readyForTurnIn,'regional field objective '+id);
          place(g.questTurnInContact(q));g.interact(p);
          check(!!g.finishQuestFromNpc(id)&&g.completedQuests.has(id),'regional NPC pays '+id);g.ui.hideMenu();
        }
      }
      for(const [idx,op] of Q.book.ops.entries()){
        for(const n of op.bosses||[])while(nextRegion<=n)clearRegionalChain(nextRegion++);
        const world=Q.surface(g);
        const src=op.site?world.getLocation(op.site):null;
        if(src){
          if(src.id==='recon_vault'){
            g.pinRecon('recovered');const eastern=g.world.getLocation('recon_vault_east');place(eastern);g.time+=1;g.interact(p);
            const pos=Q.cell(g.world.reconSite,'X');
            check(Math.hypot(pos.x-p.x,pos.y-p.y)<45&&g.world.state.vaultEntrance==='east','southern gatehouse enters the eastern branch');
            check(g.save(false)&&g.start({load:true,slot:0}),'saved eastern gatehouse approach');
            p=g.players[0];g.time+=1;place(pos);g.interact(p);
            check(Math.hypot(p.x-eastern.x,p.y-eastern.y)<150&&!g.world.isDungeon,'east entrance returns to its own surface trail');
            g.pinRecon('observed');
          }
          place(src);g.players[1].x+=500;check(!g.enterDungeon(src),'co-op arrival requires both at '+src.name);
          place(src);check(g.enterDungeon(src),'enter '+src.name);g.time+=1;
          const grid=g.world,s=grid.reconSite;
          check(walk(grid,s,'T',false,false)&&walk(grid,s,'R',false,false)&&walk(grid,s,'O',true,false)&&walk(grid,s,'K',true,true),'collision paths and shortcut · '+s.name);
          place(Q.cell(s,'T'));g.interact(p);if(s.id==='recon_cistern')g.interact(p);
          check(Q.crossingOpen(grid),'mechanism opens · '+s.name);
          check(g.save(false)&&g.start({slot:0,load:true})&&g.world.reconSite?.id===s.id&&Q.crossingOpen(g.world),'re-enter solved state · '+s.name);
          p=g.players[0];g.time+=1;
          const corrupt=g.snapshot();corrupt.dungeonStates[s.id].reconSwitch=-1;
          check(!OW.Save.validData(corrupt),'reject impossible mechanism state · '+s.name);
          const corruptPoint=g.snapshot();corruptPoint.activeDungeon.players[1].x=-999;
          check(!OW.Save.validData(corruptPoint),'reject invalid co-op interior position · '+s.name);
        }
        const paths=Q.points(g,op),snapshot=g.snapshot();
        // Exercise both paths from the same starting build. Guard kills use
        // normal damage and reward handlers to verify they unblock recovery.
        for(const route of ['recovered','observed']){
          if(route==='observed'){check(OW.Save.write(0,snapshot)&&g.start({slot:0,load:true}),'restore alternate route · '+op.title);p=g.players[0];g.time+=1;}
          const spot=Q.points(g,op)[route];place(spot);g.interact(p);
          if(route==='recovered'){
            const guards=g.world.activeEnemies.filter(e=>e.id.startsWith('recon_watch_'+op.id));
            check(guards.length===2,'guarded alternative · '+op.title);
            for(const e of guards)g.killEnemy(e,p);g.interact(p);
          }else{
            for(let n=0;n<105;n++){g.time+=.04;place(Q.points(g,op).observed);g.updateMissions(.04);}
          }
          check(g.reconDossier.evidence[op.id]?.route===route,'confirmed '+route+' · '+op.title);
        }
        const prev=p.materials;check(g.fileReconDebrief()&&!g.fileReconDebrief()&&p.materials===prev+12,'one debrief reward · '+op.title);
        const act=Q.next(g)?.act;
        if(act && act!==op.act)finishComic('Act '+(act===2?'II':'III')+' · '+Q.book.acts[act-1]);
        if(src){place(src.id==='recon_vault'?Q.cell(g.world.reconSite,'K'):g.world.start);g.interact(p);check(!g.world.isDungeon,'surface extraction · '+src.name);}
        check(g.reconDossier.filed.length===idx+1,'file order · '+op.title);
      }
      check(g.world.berlinUnlocked()&&g.checkpoint.locationId==='recon_courtyard','eight commanders plus dossier opens courtyard checkpoint');
      const finalQuest=OW.Content.quests.find(q=>q.id==='main_berlin_final');
      check(g.completedQuests.has(finalQuest.prerequisite),'the final quest prerequisite was completed at its contact');
      function speak(npc){place(npc);g.interact(p);}
      speak(g.questContact(finalQuest));
      check(g.acceptQuestFromNpc(finalQuest.id),'cleared approach accepts shipped Berlin job through its NPC');
      g.ui.hideMenu();
      const boss=g.world._createEnemy(g.world._spawns.get('boss_berlin_commander'));
      place({x:boss.x,y:boss.y+80});g.camera.x=boss.x;g.camera.y=boss.y;
      boss.hp=boss.maxHp*.65;
      g.updateAdvancedEnemy(boss,p,OW.Content.bosses[8],.04);finishComic(boss.name);
      for(let n=0;n<24;n++)g.updateAdvancedEnemy(boss,p,OW.Content.bosses[8],.04);
      check(OW.ReconCombat.record(boss)?.intelSpent===true,'observed document code silences first phase-two relay');
      g.killEnemy(boss,p);
      check(g.campaignWon&&g.ui.menu==='victory','Whisker victory enters the epilogue');
      function choose(action){const b=document.querySelector('[data-action="'+action+'"]');if(!b)throw Error('Missing '+action);b.click();}
      choose('recon-credits');choose('recon-home');
      check(!g.paused&&g.checkpoint.locationId==='town_7','credits return the party to the Dawnbridge departure hub');
      check(g.questProgress(finalQuest).readyForTurnIn&&!g.completedQuests.has(finalQuest.id),'Berlin NPC reward waits until the debrief after credits');
      speak(g.questTurnInContact(finalQuest));const gold=p.gold,payout=g.finishQuestFromNpc(finalQuest.id);
      check(payout&&p.gold===gold+finalQuest.rewardGold&&!g.finishQuestFromNpc(finalQuest.id),'Berlin NPC pays the final quest once');
      g.ui.hideMenu();
      const canonical=JSON.stringify(g.reconDossier.evidence);
      for(const c of Q.book.challenges){
        check(g.startReconExercise(c.id),'deploy '+c.title);
        g.time+=1;place(Q.cell(g.world.reconSite,'T'));
        if(!Q.crossingOpen(g.world))g.interact(p);
        for(const key of c.route){
          const op=Q.operation(g);
          if(key==='K'){place(Q.cell(g.world.reconSite,'K'));g.interact(p);continue;}
          if(c.quiet&&key==='R')g.time=Math.floor(g.time/8)*8+6;
          const route=key==='O'?'observed':'recovered',spot=Q.points(g,op)[route];place(spot);g.interact(p);
          if(key==='R'&&!c.quiet){for(const e of g.world.activeEnemies.filter(e=>e.id.startsWith('recon_watch_')&&e.hp>0))g.killEnemy(e,p);g.interact(p);}
          if(key==='O')for(let i=0;i<110;i++){g.time+=.04;place(Q.points(g,op).observed);g.updateMissions(.04);}
        }
        g.time+=1;place(g.world.start);g.interact(p);
        check(g.reconDossier.scores[c.id]===1&&!g.world.isDungeon,'scored '+c.title+' · '+JSON.stringify(g.reconDossier.run));
      }
      check(g.startReconPractice(),'deploy practice commander');
      const practice=g.world.activeEnemies.find(e=>e.reconPractice);
      g.killEnemy(practice,p);
      check(g.reconDossier.scores.whisker===1&&canonical===JSON.stringify(g.reconDossier.evidence),'practice scores separate from campaign');
      return checks;
    },oldBackup);
    assert.deepEqual(errors,[]);console.log(records.length+' checks passed');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
