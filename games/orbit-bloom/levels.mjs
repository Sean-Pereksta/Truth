const defineLevel = ({ layout, ships, ...details }) => {
    const stations = [];
    const spawns = [];
    const width = layout[0].length;
    for (const [y, row] of layout.entries()) {
        if (row.length !== width) throw new Error(`Uneven row ${y} in ${details.id}: ${row}`);
        for (const [x, character] of [...row].entries()) {
            const station = STATION_CHARS[character];
            if (station) {
                const [type, variant, label] = station;
                stations.push({ id: `${character}-${x}-${y}`, type, variant, label, x, y });
            }
            if (/^[1-4]$/.test(character)) spawns[Number(character) - 1] = { x, y };
        }
    }
    return {
        rootGraceMs: 11000,
        bloomGraceMs: 14000,
        durationMs: 180000,
        cutoffMs: 134000,
        orderIntervalMs: 17000,
        patienceMs: 62000,
        skipNeeds: [],
        cooldownMs: 0,
        ships: ships ?? null,
        weather: null,
        ...details,
        layout,
        width,
        height: layout.length,
        stations,
        spawns,
    };
};

